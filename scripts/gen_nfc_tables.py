#!/usr/bin/env python3
"""Write `Tyr/Tokenizer/NfcData.lean`, the tables of `Tyr/Tokenizer/Nfc.lean`,
from this Python's `unicodedata`:

    python3 scripts/gen_nfc_tables.py

Hangul syllables are left out; `Nfc.lean` handles them algorithmically."""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "Tyr" / "Tokenizer" / "NfcData.lean"
HANGUL = range(0xAC00, 0xD7A4)


def main() -> int:
    chars = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
    # Runs of code points sharing a nonzero canonical combining class.
    classes, run = [], None
    for cp in chars:
        ccc = unicodedata.combining(chr(cp))
        if run and run[1] == cp - 1 and run[2] == ccc:
            run[1] = cp
        else:
            if run and run[2]:
                classes.append(run)
            run = [cp, cp, ccc]
    if run and run[2]:
        classes.append(run)
    decompositions, compositions = [], []
    for cp in chars:
        mapping = unicodedata.decomposition(chr(cp))
        if not mapping or mapping.startswith("<") or cp in HANGUL:
            continue
        full = unicodedata.normalize("NFD", chr(cp))
        decompositions.append((cp, [ord(c) for c in full]))
        parts = [int(x, 16) for x in mapping.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            compositions.append((parts[0], parts[1], cp))

    def hexes(values):
        return " ".join(f"{v:X}" for v in values)

    text = f"""/-
  Tyr/Tokenizer/NfcData.lean

  Generated by `scripts/gen_nfc_tables.py` from Unicode {unicodedata.unidata_version}; do not edit.
  `combiningClasses`: `start end class` runs of nonzero canonical combining
  class. `decompositions`: `cp:full canonical decomposition`. `compositions`:
  `first second composite` for each primary composite. Hex, `;`-separated.
-/

namespace tokenizer.nfc

def combiningClasses : String :=
  "{';'.join(hexes(r) for r in classes)}"

def decompositions : String :=
  "{';'.join(f'{cp:X}:{hexes(full)}' for cp, full in decompositions)}"

def compositions : String :=
  "{';'.join(hexes(c) for c in compositions)}"

end tokenizer.nfc
"""
    OUT.write_text(text)
    print(f"{OUT}: {len(classes)} class runs, {len(decompositions)} decompositions, "
          f"{len(compositions)} compositions (Unicode {unicodedata.unidata_version})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
