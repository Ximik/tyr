#!/usr/bin/env bash
# Regenerate Tyr/Model/KittenTTS/Checkpoint.lean from the pinned Kokoro v1 checkpoint.
set -euo pipefail
repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"
revision=f3ff3571791e39611d31c381e3a41a3af07b4987
sha256=496dba118d1a58f5f3db2efc88dbdc216e0483fc89fe6e47ee1f2c53f18ad1e4
dir=output/kittentts-record
mkdir -p "$dir"
checkpoint=$dir/kokoro-v1_0.pth
if ! echo "$sha256  $checkpoint" | sha256sum --check --status 2>/dev/null; then
  curl -fL --retry 3 -o "$checkpoint" \
    "https://huggingface.co/hexgrad/Kokoro-82M/resolve/$revision/kokoro-v1_0.pth"
  echo "$sha256  $checkpoint" | sha256sum --check
fi
if [[ ! -x $dir/venv/bin/python ]]; then
  python3 -m venv "$dir/venv"
  "$dir/venv/bin/pip" install --quiet numpy==2.5.4 safetensors==0.8.0 torch==2.10.0 \
    --extra-index-url https://download.pytorch.org/whl/cpu
fi
"$dir/venv/bin/python" scripts/kokoro_to_safetensors.py \
  --checkpoint "$checkpoint" --checkpoint-out "$dir/model.safetensors"
lake build GenerateSafeTensorsRecord >/dev/null
.lake/build/bin/GenerateSafeTensorsRecord "$dir/model.safetensors" torch.kittentts.KokoroCheckpoint \
  | sed '1s/.*/-- Generated by `scripts\/kittentts_record.sh`; do not edit./' > Tyr/Model/KittenTTS/Checkpoint.lean
